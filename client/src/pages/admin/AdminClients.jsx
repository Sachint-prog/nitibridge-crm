import React, { useEffect, useState } from 'react';
import axios from '../../api';
import Pagination from '../../components/Pagination';

const AdminClients = () => {
    const [clients, setClients] = useState([]);
    const [loading, setLoading] = useState(true);
    
    const [currentPage, setCurrentPage] = useState(1);
    const [entriesPerPage, setEntriesPerPage] = useState(10);

    useEffect(() => {
        fetchClients();
    }, []);

    const fetchClients = async () => {
        try {
            const res = await axios.get('/admin/clients');
            if (res.data.success) {
                setClients(res.data.clients);
            }
        } catch (err) {
            console.error(err);
        } finally {
            setLoading(false);
        }
    };

    const updateType = async (id, newType) => {
        try {
            const res = await axios.post(`/admin/client/edit/${id}`, { clientType: newType });
            if (res.data.success) {
                fetchClients(); // Refresh list to reflect changes
            }
        } catch (err) {
            alert('Failed to update category');
        }
    };

    const indexOfLastEntry = currentPage * entriesPerPage;
    const indexOfFirstEntry = indexOfLastEntry - entriesPerPage;
    const currentEntries = clients.slice(indexOfFirstEntry, indexOfLastEntry);

    return (
        <div className="glass-panel" style={{ padding: '2rem' }}>
            <h2 style={{ marginBottom: '1rem' }}>Client Management</h2>
            <p style={{ color: 'var(--text-secondary)', marginBottom: '2rem' }}>Review clients generated by employees and adjust their categorization priority.</p>

            <div style={{ overflowX: 'auto' }}>
                <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left' }}>
                    <thead>
                        <tr style={{ borderBottom: '2px solid var(--border-color)' }}>
                            <th style={{ padding: '1rem 0.5rem' }}>Created At</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Client ID</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Name</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Contact Number</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Added By</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Current Type</th>
                            <th style={{ padding: '1rem 0.5rem' }}>Edit Type</th>
                        </tr>
                    </thead>
                    <tbody>
                        {currentEntries.map(client => (
                            <tr key={client._id} style={{ borderBottom: '1px solid var(--border-color)' }}>
                                <td style={{ padding: '1rem 0.5rem', fontSize: '0.85rem', color: 'var(--text-muted)' }}>
                                    {new Date(client.createdAt).toDateString()}
                                </td>
                                <td style={{ padding: '1rem 0.5rem', fontWeight: 'bold', color: 'var(--teal)' }}>
                                    {client.userId}
                                </td>
                                <td style={{ padding: '1rem 0.5rem', fontWeight: '600' }}>
                                    {client.name}
                                </td>
                                <td style={{ padding: '1rem 0.5rem' }}>
                                    {client.contactNumber}
                                </td>
                                <td style={{ padding: '1rem 0.5rem' }}>
                                    {client.addedBy ? (
                                        <>
                                            {client.addedBy.name}
                                            {!client.addedBy.isActive && (
                                                <div><span style={{ fontSize: '0.6rem', padding: '0.1rem 0.3rem', borderRadius: '4px', background: '#fef2f2', color: '#ef4444', border: '1px solid #fecaca' }}>Fired</span></div>
                                            )}
                                        </>
                                    ) : 'Unknown'}
                                </td>
                                <td style={{ padding: '1rem 0.5rem' }}>
                                    <span className={`badge ${client.clientType.toLowerCase()}`}>{client.clientType}</span>
                                </td>
                                <td style={{ padding: '1rem 0.5rem' }}>
                                    <div style={{ display: 'flex', gap: '0.5rem' }}>
                                        <select 
                                            className="form-control" 
                                            value={client.clientType} 
                                            onChange={(e) => updateType(client._id, e.target.value)}
                                            style={{ padding: '0.25rem 0.5rem', fontSize: '0.875rem', width: 'auto' }}
                                        >
                                            <option value="Hot">Hot</option>
                                            <option value="Warm">Warm</option>
                                            <option value="Cold">Cold</option>
                                        </select>
                                    </div>
                                </td>
                            </tr>
                        ))}
                        {currentEntries.length === 0 && (
                            <tr>
                                <td colSpan="7" style={{ padding: '2rem', textAlign: 'center', color: 'var(--text-muted)' }}>No clients found.</td>
                            </tr>
                        )}
                    </tbody>
                </table>
            </div>

            <Pagination 
                totalEntries={clients.length}
                entriesPerPage={entriesPerPage}
                currentPage={currentPage}
                onPageChange={setCurrentPage}
                onEntriesPerPageChange={(val) => {setEntriesPerPage(val); setCurrentPage(1);}}
            />
        </div>
    );
};
export default AdminClients;
